from __future__ import annotations

import platform
import sys
from datetime import datetime, timezone
from functools import lru_cache
from pathlib import Path
from typing import Any

import pandas as pd

MARKER = "#"


@lru_cache(maxsize=1)
def _machine() -> str:
    import psutil

    return (
        f"{_cpu_model()}, {psutil.cpu_count(logical=False)} cores, "
        f"{psutil.virtual_memory().total / 1024**3:.0f} GiB, "
        f"{platform.system()} {platform.release()}, Python {sys.version.split()[0]}"
    )


def _cpu_model() -> str:
    cpuinfo = Path("/proc/cpuinfo")
    if cpuinfo.exists():
        for line in cpuinfo.read_text().splitlines():
            if line.startswith("model name"):
                return line.split(":", 1)[1].strip()
    return platform.processor() or platform.machine()


def fields(source: str, **extra: Any) -> dict[str, str]:
    values = {
        "generated": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC"),
        "source": source,
        "machine": _machine(),
    }
    values.update({key: str(value) for key, value in extra.items()})
    return values


def header(source: str, **extra: Any) -> str:
    lines = [f"{MARKER} generated by causality-bench, do not edit by hand"]
    lines += [f"{MARKER} {key}: {value}" for key, value in fields(source, **extra).items()]
    return "\n".join(lines) + "\n"


def write_csv(frame: pd.DataFrame, path: Path, source: str, **extra: Any) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as handle:
        handle.write(header(source, rows=len(frame), **extra))
        frame.to_csv(handle, index=False)
    return path


def read_csv(path: Path | str) -> pd.DataFrame:
    path = Path(path)
    with path.open() as handle:
        skip = sum(1 for line in handle if line.startswith(MARKER))
    return pd.read_csv(path, skiprows=skip)


def read_stamp(path: Path | str) -> dict[str, str]:
    stamp = {}
    with Path(path).open() as handle:
        for line in handle:
            if not line.startswith(MARKER):
                break
            body = line[len(MARKER) :].strip()
            if ": " in body:
                key, value = body.split(": ", 1)
                stamp[key] = value
    return stamp


def png_metadata(source: str, **extra: Any) -> dict[str, str]:
    values = fields(source, **extra)
    return {
        "Software": "causality-bench",
        "Creation Time": values["generated"],
        **{key: value for key, value in values.items() if key != "generated"},
    }
